"""The seam between the HTTP/MCP/agent layer (W3) and the core (W2).

W2 implements these. W3 only calls these. Signatures are the contract.
`workspaces` is the read scope (e.g. ["acme", "v-123"]); writes go to workspaces[-1].
"""
from canon.models import (
    Activity, Alert, AskRequest, AskResult, Briefing, BriefingRequest, CheckRequest,
    CheckResult, Decision, DecisionDetail, EvalReport, ExpertRequest, IngestRequest,
    IngestResult, Person, ResolveRequest, Source,
)


async def ingest(req: IngestRequest, workspaces: list[str]) -> IngestResult: ...
async def ask(req: AskRequest, workspaces: list[str]) -> AskResult: ...
async def briefing(req: BriefingRequest, workspaces: list[str]) -> Briefing: ...
async def check(req: CheckRequest, workspaces: list[str]) -> CheckResult: ...
async def expert(req: ExpertRequest, workspaces: list[str]) -> AskResult: ...
async def search_decisions(query: str, workspaces: list[str], limit: int = 5) -> list[Decision]: ...
async def list_decisions(workspaces: list[str], status: str | None = None, topic: str | None = None) -> list[Decision]: ...
async def get_decision(decision_id: str, workspaces: list[str]) -> DecisionDetail: ...
async def list_alerts(workspaces: list[str], status: str | None = None) -> list[Alert]: ...
async def resolve_alert(alert_id: str, req: ResolveRequest, workspaces: list[str]) -> Alert: ...
async def get_source(source_id: str, workspaces: list[str]) -> Source: ...
async def list_activity(workspaces: list[str], since_iso: str | None = None) -> list[Activity]: ...
async def log_activity(workspace: str, actor: str, action: str, summary: str,
                       ref_ids: list[str] | None = None, verdict: str | None = None) -> None: ...
async def list_people(workspaces: list[str]) -> list[Person]: ...
async def eval_report() -> EvalReport: ...
async def reset_workspace(workspace: str) -> None: ...
